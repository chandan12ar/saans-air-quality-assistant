export type Translate = (key: StringKey, ...args: Array<string | number>) => string;

export function makeTranslator(lang: Language): Translate {
  return (key, ...args) => STRINGS[lang][key].replace(/\{(\d+)\}/g, (_, i: string) => String(args[Number(i)] ?? ""));
}
